-- Schema idempotente para a API de ofertas. Não apaga dados existentes.
CREATE TABLE IF NOT EXISTS public.ofertas_gemini (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 supermercado TEXT, descricao TEXT, peso_quantidade TEXT,
 preco NUMERIC(12,2) CHECK (preco IS NULL OR preco >= 0),
 dados_originais JSONB NOT NULL DEFAULT '{}'::jsonb,
 assinatura TEXT, registrado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.historico_precos_gemini (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 oferta_id BIGINT NOT NULL REFERENCES public.ofertas_gemini(id) ON DELETE CASCADE,
 preco NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
 registrado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 origem TEXT NOT NULL DEFAULT 'api', observacao TEXT
);
-- A assinatura deve ser fornecida pela API (supermercado + produto + apresentação),
-- não derivada do JSON inteiro, para permitir atualizar o mesmo produto e registrar histórico.
DO $
BEGIN
 IF EXISTS (
   SELECT 1 FROM information_schema.columns
   WHERE table_schema='public' AND table_name='ofertas_gemini'
     AND column_name='assinatura' AND is_generated='ALWAYS'
 ) THEN
   ALTER TABLE public.ofertas_gemini ALTER COLUMN assinatura DROP EXPRESSION;
 END IF;
END $;
CREATE UNIQUE INDEX IF NOT EXISTS ofertas_gemini_assinatura_unique ON public.ofertas_gemini(assinatura);
CREATE INDEX IF NOT EXISTS historico_precos_gemini_oferta_data_idx ON public.historico_precos_gemini(oferta_id, registrado_em DESC);
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ofertas_gemini' AND column_name='preco' AND data_type='numeric') THEN RAISE EXCEPTION 'ofertas_gemini.preco deve ser NUMERIC'; END IF;
 IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ofertas_gemini' AND column_name='registrado_em' AND data_type='timestamp with time zone') THEN RAISE EXCEPTION 'ofertas_gemini.registrado_em deve ser TIMESTAMPTZ'; END IF;
 IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ofertas_gemini' AND column_name='dados_originais' AND data_type='jsonb') THEN RAISE EXCEPTION 'ofertas_gemini.dados_originais deve ser JSONB'; END IF;
 IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='historico_precos_gemini' AND column_name='preco' AND data_type='numeric') THEN RAISE EXCEPTION 'historico_precos_gemini.preco deve ser NUMERIC'; END IF;
END $$;
